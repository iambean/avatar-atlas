export function declarations(ids = []) {
  return `export type AvatarId = ${ids.map(id => JSON.stringify(id)).join(' | ') || 'string'};
export interface Avatar { id: string; title: string; category: string; tags: string[]; url: string; formats: {webp: string}; age?: number; gender?: string; direction?: string; temperament?: string; retired?: boolean; ageGroup?: string; ageGroupLabel?: string; genderLabel?: string; region?: string; isDefault?: boolean; creator?: string; aiGenerated?: boolean; creationMethod?: string; sizes?: {webp: number}; bytes?: number; license: string; licenseUrl?: string; sourceUrl?: string; sha256: string; [key: string]: unknown; }
export interface AvatarFilters { category?: string; gender?: string; minAge?: number; maxAge?: number; query?: string; }
export interface AvatarManifest { version: string; defaultAvatarId: string; items: Avatar[]; [key: string]: unknown; }
`;
}

export function runtimeModule(manifest, typescript = false) {
  const types = typescript ? declarations(manifest.items.map(a => a.id)) : '';
  return `// Generated by Avatar Atlas. Run avatar-atlas update to refresh.
${types}export const manifest${typescript ? ': AvatarManifest' : ''} = ${JSON.stringify(manifest, null, 2)};
export const avatars = manifest.items.filter(a => !a.retired);
export const defaultAvatarId = manifest.defaultAvatarId;
const byId = new Map${typescript ? '<string, Avatar>' : ''}(manifest.items.map(a => [a.id, a]));
export function getAvatar(id${typescript ? ': string' : ''}) { return byId.get(id); }
export const defaultAvatar = byId.get(defaultAvatarId)${typescript ? '!' : ''};
export function avatarUrl(id${typescript ? ': string' : ''} = defaultAvatarId) { return (getAvatar(id) || defaultAvatar).url; }
export function findAvatars(filters${typescript ? ': AvatarFilters' : ''} = {}) {
  const query = (filters.query || '').trim().toLowerCase();
  return avatars.filter(a => (!filters.category || a.category === filters.category)
    && (!filters.gender || a.gender === filters.gender)
    && (filters.minAge == null || (a.age != null && a.age >= filters.minAge))
    && (filters.maxAge == null || (a.age != null && a.age <= filters.maxAge))
    && (!query || [a.id, a.title, ...a.tags].join(' ').toLowerCase().includes(query)));
}
`;
}

export function runtimeTypes(manifest) {
  return declarations(manifest.items.map(a => a.id)) + `export declare const manifest: AvatarManifest;
export declare const avatars: Avatar[];
export declare const defaultAvatarId: string;
export declare const defaultAvatar: Avatar;
export declare function getAvatar(id: string): Avatar | undefined;
export declare function avatarUrl(id?: string): string;
export declare function findAvatars(filters?: AvatarFilters): Avatar[];
`;
}
